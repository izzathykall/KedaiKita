export function calculateExpression(expression){
 let compact=expression.replaceAll('×','*').replaceAll('÷','/').replaceAll('−','-').replace(/\s/g,'');if(compact.startsWith('-'))compact='0'+compact;
 if(!/^\d*\.?\d+(?:[+*/-]\d*\.?\d+)*$/.test(compact))throw new Error('Lengkapkan kiraan dahulu.');
 const tokens=compact.match(/\d*\.?\d+|[+*/-]/g),parts=[Number(tokens[0])];
 for(let i=1;i<tokens.length;i+=2){const op=tokens[i],n=Number(tokens[i+1]);if(op==='*'||op==='/'){if(op==='/'&&n===0)throw new Error('Tidak boleh bahagi dengan sifar.');const prev=parts.pop();parts.push(op==='*'?prev*n:prev/n)}else parts.push(op,n)}
 let value=parts[0];for(let i=1;i<parts.length;i+=2)value+=parts[i]==='+'?parts[i+1]:-parts[i+1];
 if(!Number.isFinite(value)||Math.abs(value)>1e12)throw new Error('Nilai terlalu besar.');return Math.round(value*1e8)/1e8;
}

